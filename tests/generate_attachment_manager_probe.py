#!/usr/bin/env python3
"""Compile real attachment-manager callbacks against UI-only stubs in the PDF harness."""
from pathlib import Path
root = Path(__file__).resolve().parents[1]
source = (root / 'MainWindow.Attachments.cs').read_text()
# Only external launch and AppData location are seams; all callback/session logic is real.
def must_replace(text, old, new):
    # A seam that no longer matches would silently launch a real PDF app or read the real RED profile.
    if old not in text:
        raise SystemExit('probe seam not found: ' + old)
    return text.replace(old, new)
source = must_replace(source, 'using var process = Process.Start(PdfAppLauncher.StartInfoFor(monitor.WorkingPath)); // F-017 A1: the PDF app from Settings', '_ = monitor.StartInfo;')
source = must_replace(source, 'if (JobFilesService.IsBlockedFor(InspectorProfileService.Load()?.UserType))', 'if (false)')
source = must_replace(source, 'Path.Combine(AppIdentity.LocalAppDataPath, "PdfAttachments")', 'ProbeRoot')
# Include the actual leave guard too, so pending-add navigation is executed, not inferred.
orientation = (root / 'MainWindow.OrientationPdf.cs').read_text()
start = orientation.index('        private bool FinishOrientationEditing(')
brace = orientation.index('{', start)
depth = 1
end = brace + 1
while depth:
    depth += (orientation[end] == '{') - (orientation[end] == '}')
    end += 1
source = source[:source.rfind('    }')] + orientation[start:end] + '\n' + source[source.rfind('    }'):]
(root / 'tests/OrientationPdfHarness/AttachmentManagerProbe.Generated.cs').write_text(
    '// Generated by tests/generate_attachment_manager_probe.py from production callbacks.\n#nullable enable\n' + source)
dialog = (root / 'AttachmentsWindow.xaml.cs').read_text()
dialog = dialog.replace('using Microsoft.Win32;', 'using AttachmentDialog.Stubs;')
dialog = dialog.replace('using System.Windows;\n', '')
dialog = dialog.replace('namespace InspectionEditor', 'namespace AttachmentDialog')
(root / 'tests/OrientationPdfHarness/AttachmentDialogProbe.Generated.cs').write_text(
    '// Generated from AttachmentsWindow.xaml.cs; only UI types/namespaces are seams.\n#nullable enable\n' + dialog)
print('Generated production attachment manager and confirmation dialog probes')
